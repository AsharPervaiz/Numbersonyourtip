// Reusable icon circle wrapper
export function IconCircle({
  color,
  size = 44,
  children,
}: {
  color: IconColor;
  size?: number;
  children: React.ReactNode;
}) {
  const { bg, color: iconColor } = iconColorMap[color];
  return (
    <span
      className="menu-icon-circle"
      style={{
        backgroundColor: bg,
        color: iconColor,
        width: size,
        height: size,
        minWidth: size,
        borderRadius: "50%",
        display: "inline-flex",
        alignItems: "center",
        justifyContent: "center",
      }}
    >
      {children}
    </span>
  );
}

